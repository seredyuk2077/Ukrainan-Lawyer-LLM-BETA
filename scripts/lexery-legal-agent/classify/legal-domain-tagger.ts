/**
 * [U2b] LegalDomainTagger — rule-based baseline (LEX-84)
 */
import type { LegalDomain } from './types.js';

// Тільки структурні збіги: назви/абревіатури актів, явні галузі. НЕ словник фактів — складні кейси йдуть in LLM.
// Criminal patterns охоплюють: скорочення актів (ККУ, КК України, КПК), термінологію КК (тілесні ушкодження,
// вид/форма вини, злочин, кримінальн*), посилання на статті КК, держтаємницю/шпигунство.
// Ці слова є галузевою юридичною лексикою кримінального права — не евристики під конкретні кейси.
const DOMAIN_RULES: { pattern: RegExp; domain: LegalDomain }[] = [
  {
    // \S* замість \w+ для кириличних закінчень (\w не матчить кирилицю в JS).
    // Покриває: коди актів (ККУ, КК України, КПК), юридичну лексику КК (злочин, тілесні ушкодження,
    // вид/форма вини, кримінальна відповідальність), посилання ст.N КК, держтаємниця, шпигунство.
    pattern: /(?:^|[\s\W])(ККУ|КК\s+України|кримінальн\S+|Кримінальний\s+(?:кодекс|закон)|КПК|злочин\S*|тілесн\S+\s+ушкодж\S+|ст\.\s*\d+\s*(?:КК|ккУ)(?:\s|$)|вид\S*\s+вини|форм[аи]\s+вини|умисн\S+\s+(?:вбивств\S+|заподіянн\S+)|державн\S+\s+таємниц\S+|шпигун\S*)(?:[\s\W]|$)/i,
    domain: 'criminal',
  },
  { pattern: /(?:^|[\s\W])(освіт\w*|дошкільн\w*|дискримінаці\w*|закон\s*про\s*освіту|протидії\s*дискримінації|щепленн\w*|вакцинаці\w*|заклад\w*\s*освіт)(?:[\s\W]|$)/i, domain: 'education' },
  { pattern: /(?:^|[\s\W])(ЦКУ|цивільний кодекс|цивільний|позов|договір|спадок|право власності|власник|нерухомість|спадщина)(?:[\s\W]|$)/i, domain: 'civil' },
  { pattern: /(?:^|[\s\W])(КЗпП|трудовий|звільнення|прогул|відпустка|працівник)(?:[\s\W]|$)/i, domain: 'labor' },
  { pattern: /(?:^|[\s\W])(ПКУ|податок|податковий|ДПС|ПДВ|податкова|податкової|рішення податкової)(?:[\s\W]|$)/i, domain: 'tax' },
  { pattern: /(?:^|[\s\W])(КАС|адмін|адміністративний|оскаржити рішення)(?:[\s\W]|$)/i, domain: 'admin' },
  { pattern: /(?:^|[\s\W])(МОЗ|охорона здоров'я|смерть мозку|інтенсивн|реанімаці|штучн[^\s]*\s*підтримання|відділення\s*анестезіології)(?:[\s\W]|$)/i, domain: 'health' },
  { pattern: /(?:^|[\s\W])(корпоративний|ТОВ|АТ|засновник|статут)(?:[\s\W]|$)/i, domain: 'corporate' },
];

export function tagLegalDomain(query: string): LegalDomain {
  const q = query.trim();
  if (!q) return 'general';

  for (const { pattern, domain } of DOMAIN_RULES) {
    if (pattern.test(q)) return domain;
  }

  return 'general';
}
